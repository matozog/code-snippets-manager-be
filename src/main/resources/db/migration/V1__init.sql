create table code_snippet
(
    id_snippet           bigint generated by default as identity primary key,
    name                 varchar(255) not null,
    description          text,
    content              text,
    favorite             boolean      not null default false,
    programming_language varchar(255),
    type                 varchar(255),
    added_from           varchar(255),
    added_date           timestamp(6)
);

create table tag
(
    id_tag     bigint generated by default as identity primary key,
    name       varchar(255) not null,
    added_date timestamp(6),
    constraint uk_tag_name unique (name)
);

create table snippet_tag
(
    id_snippet bigint not null references code_snippet (id_snippet) on delete cascade,
    id_tag     bigint not null references tag (id_tag) on delete cascade,
    primary key (id_snippet, id_tag)
);

create index ix_snippet_tag_id_tag on snippet_tag (id_tag);

-- Users signing in with Google; snippets and tags become private to their owner.
-- The owner columns are NOT NULL, so this migration expects tables without data (true for the first deployment).

create table app_user
(
    id         bigint generated by default as identity primary key,
    google_sub varchar(255)                not null,
    email      varchar(255),
    name       varchar(255),
    created_at timestamp(6) with time zone not null,
    constraint uk_app_user_google_sub unique (google_sub)
);

alter table code_snippet
    add column owner_id bigint not null references app_user (id) on delete cascade;

create index ix_code_snippet_owner_id on code_snippet (owner_id);

-- tag names are unique per user, not globally
alter table tag
    add column owner_id bigint not null references app_user (id) on delete cascade;

alter table tag
    drop constraint uk_tag_name;

alter table tag
    add constraint uk_tag_owner_id_name unique (owner_id, name);
